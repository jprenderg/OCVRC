"""Run the OCVRC_Github pipeline using the existing, independently tested scripts.

Run in Spyder's current IPython console to expose final df_* variables.
See README_Run_OCVRC.md. Paths resolve from this file's project root.
"""
from __future__ import annotations

import configparser
import runpy
import sys
import time
import traceback
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent
MODULE_DIRS = [ROOT, *(ROOT / d for d in ('source_ingestion', 'image_retrieval', 'radio_processing', 'catalog_integration', 'database', 'validation'))]
for directory in MODULE_DIRS:
    path = str(directory.resolve())
    if path not in sys.path:
        sys.path.insert(0, path)
CONFIG_PATH = ROOT / 'config.txt'
if not CONFIG_PATH.is_file():
    raise FileNotFoundError(CONFIG_PATH)

config = configparser.ConfigParser(interpolation=None)
config.read(CONFIG_PATH, encoding='utf-8')
OUTPUT = Path(config.get('PATHS', 'OUTPUT_DIR', fallback='output')).expanduser()
OUTPUT = OUTPUT if OUTPUT.is_absolute() else ROOT / OUTPUT
FINAL = OUTPUT / 'final'

# A stage may be omitted deliberately. Intermediate files from earlier runs
# MUST NOT silently be reused as though generated by this invocation.
STAGES = [
    ('SOURCE_INGESTION', 'source_ingestion/Build_Source_Name_Class.py', True),
    ('VLASS_IMAGES', 'image_retrieval/Get_VLASS_Images.py', True),
    ('RACS_IMAGES', 'image_retrieval/Get_RACS_Images.py', True),
    ('VLASS_NEIGHBORS', 'radio_processing/VLASS_Neighbor_Detection.py', True),
    ('RACS_NEIGHBORS', 'radio_processing/RACS_Neighbor_Detection.py', True),
    ('VLASS_GLS', 'radio_processing/VLASS_GLS_PSF_Fit.py', True),
    ('RACS_GLS', 'radio_processing/RACS_GLS_PSF_Fit.py', True),
    ('RADIO_TABLE', 'radio_processing/Build_Radio_Measurements.py', True),
    ('GAIA', 'catalog_integration/Get_Gaia_DR3.py', True),
    ('2MASS', 'catalog_integration/Get_2MASS.py', True),
    ('GALEX', 'catalog_integration/Get_GALEX.py', True),
    ('LOTSS', 'catalog_integration/Get_LoTSS_DR2.py', True),
    ('ROSAT', 'catalog_integration/Get_ROSAT.py', True),
    ('XMM', 'catalog_integration/Get_XMM.py', True),
    ('CHANDRA', 'catalog_integration/Get_Chandra.py', True),
    ('EROSITA', 'catalog_integration/Get_eROSITA.py', True),
    ('FINAL_DATABASE', 'database/Build_Final_Database.py', True),
    ('SQLITE_DATABASE', 'database/Build_SQLite_Database.py', True),
    ('VALIDATION', 'validation/Run_Validation.py', True),
]

# NOTE: "enabled" means execute; it does NOT mean the existing output file is
# necessarily current. For a fresh source list, execute ALL stages or remove
# the disabled survey's old outputs before constructing the final database.
enabled = {name: config.getboolean('PIPELINE', name, fallback=default)
           for name, _, default in STAGES}
STOP_ON_ERROR = config.getboolean('PIPELINE', 'STOP_ON_ERROR', fallback=True)

# Prevent accidental reuse of survey files when a disabled stage is selected.
SURVEY_OUTPUTS = {
    'GAIA': ['Gaia_measurements.pkl'],
    '2MASS': ['2MASS_measurements.pkl'],
    'GALEX': ['GALEX_measurements.pkl'],
    'LOTSS': ['LoTSS_measurements.pkl'],
    'ROSAT': ['ROSAT_measurements.pkl'],
    'XMM': ['XMM_measurements.pkl'],
    'CHANDRA': ['Chandra_measurements.pkl'],
    'EROSITA': ['eROSITA_measurements.pkl'],
}

# Do not allow a partial pipeline to accidentally combine stale data; such a
# run is useful for debugging but requires final builder to be disabled.
if enabled['FINAL_DATABASE']:
    skipped = [s for s, _, _ in STAGES if s not in ('FINAL_DATABASE', 'SQLITE_DATABASE', 'VALIDATION') and not enabled[s]]
    if skipped:
        raise ValueError(
            'FINAL_DATABASE is enabled, but these stages are disabled: '
            + ', '.join(skipped) + '. Set FINAL_DATABASE = FALSE for partial runs. '
            'This protects against combining stale survey files.'
        )

if enabled['SQLITE_DATABASE'] and not enabled['FINAL_DATABASE']:
    raise ValueError('SQLITE_DATABASE requires FINAL_DATABASE = TRUE.')

if enabled['VALIDATION'] and (not enabled['FINAL_DATABASE'] or not enabled['SQLITE_DATABASE']):
    raise ValueError('VALIDATION requires FINAL_DATABASE = TRUE and SQLITE_DATABASE = TRUE.')

for name, relative, _ in STAGES:
    if enabled[name] and not (ROOT / relative).is_file():
        raise FileNotFoundError(f'{name}: missing {ROOT / relative}')

# Existing neighbor scripts may execute plotting even at INDEX=-1, and their
# plotting INDEX variable is not consistently read from config.txt. The runner
# leaves those standalone scripts unchanged, so users can still inspect plots.
# Important: when testing the full pipeline, close figures as necessary.

stage_results = []
previous_cwd = Path.cwd()
try:
    # Individual scripts compute ROOT from __file__, but some relative calls
    # also assume the project working directory.
    import os
    os.chdir(ROOT)
    print('\nOCVRC_Github MASTER RUN')
    print('=' * 60)
    print('Project:', ROOT)
    print('Config:', CONFIG_PATH)
    for name, relative, _ in STAGES:
        if not enabled[name]:
            stage_results.append({'STAGE': name, 'STATUS': 'SKIPPED', 'SECONDS': 0., 'ERROR': ''})
            continue
        print(f'\n[{name}] {relative}')
        started = time.monotonic()
        try:
            # run_name not __main__: mirrors Spyder runfile execution while
            # isolating each script's global namespace from the master runner.
            runpy.run_path(str(ROOT / relative), run_name='__main__')
        except Exception as exc:
            duration = time.monotonic() - started
            stage_results.append({'STAGE': name, 'STATUS': 'FAILED',
                                  'SECONDS': round(duration, 2),
                                  'ERROR': f'{type(exc).__name__}: {exc}'[:300]})
            print(f'ERROR in {name}: {type(exc).__name__}: {exc}')
            if name == 'SOURCE_INGESTION' and type(exc).__name__ == 'SimbadUnavailableError':
                print('[SOURCE_INGESTION] SIMBAD unavailable and no verified reusable results.')
                print('[SOURCE_INGESTION] Previously saved outputs are untouched.')
                print('[SOURCE_INGESTION] Restart when SIMBAD is available, or run standalone validation.')
                # Stop cleanly without a long, unhelpful Astroquery/PyVO traceback.
                break
            traceback.print_exc(limit=4)
            raise RuntimeError(f'Master pipeline stopped at {name}.') from exc
        else:
            duration = time.monotonic() - started
            stage_results.append({'STAGE': name, 'STATUS': 'COMPLETED',
                                  'SECONDS': round(duration, 2), 'ERROR': ''})
            print(f'[{name}] completed in {duration:.1f}s')
finally:
    import os
    os.chdir(previous_cwd)
    df_pipeline_status = pd.DataFrame(stage_results,
        columns=['STAGE', 'STATUS', 'SECONDS', 'ERROR'])
    OUTPUT.mkdir(parents=True, exist_ok=True)
    df_pipeline_status.to_pickle(OUTPUT / 'pipeline_status.pkl')
    print('\nMASTER PIPELINE STAGES')
    print('=' * 60)
    print(df_pipeline_status[['STAGE', 'STATUS', 'SECONDS']].to_string(index=False))

# Expose final DataFrames in Spyder's Variable Explorer only on successful completion.
if not any(row['STATUS'] == 'FAILED' for row in stage_results) and enabled['FINAL_DATABASE']:
    for label in ('source', 'name', 'class', 'period', 'measurement'):
        path = FINAL / f'{label}.pkl'
        if not path.exists():
            raise FileNotFoundError(f'Expected final output missing: {path}')
        globals()[f'df_{label}'] = pd.read_pickle(path)
    print('\nFINAL TABLES')
    for label in ('source', 'name', 'class', 'period', 'measurement'):
        print(f'{label:12s} {len(globals()[f"df_{label}"]):,} rows')
    print('Final outputs:', FINAL)
